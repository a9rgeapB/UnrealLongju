bool SameType(const FEdGraphPinType& A,const FEdGraphPinType& B)
{
	return A.PinCategory==B.PinCategory && A.PinSubCategory==B.PinSubCategory &&
		A.PinSubCategoryObject==B.PinSubCategoryObject && A.ContainerType==B.ContainerType && A.PinValueType==B.PinValueType;
}
FString Describe(const UEdGraphPin* Pin)
{
	return Pin->GetOwningNode()->GetPathName()+TEXT(":")+Pin->PinName.ToString();
}
FProperty* DeclaredProperty(UEdGraphPin* Pin)
{
	if (Pin->ParentPin && Pin->ParentPin->PinType.PinCategory==UEdGraphSchema_K2::PC_Struct)
	{
		if (auto* Struct=Cast<UScriptStruct>(Pin->ParentPin->PinType.PinSubCategoryObject.Get()))
		{
			FString Name=Pin->PinName.ToString(),Prefix=Pin->ParentPin->PinName.ToString()+TEXT("_");
			Name.RemoveFromStart(Prefix); return FindFProperty<FProperty>(Struct,*Name);
		}
	}
	auto* Node=Pin->GetOwningNode();
	if (auto* Variable=Cast<UK2Node_Variable>(Node))
	{
		FProperty* Property=Variable->GetPropertyForVariable();
		return Property && Property->GetFName()==Pin->PinName ? Property : nullptr;
	}
	if (auto* Call=Cast<UK2Node_CallFunction>(Node)) { return Call->GetTargetFunction() ? FindFProperty<FProperty>(Call->GetTargetFunction(),Pin->PinName) : nullptr; }
	if (auto* Struct=Cast<UK2Node_StructOperation>(Node)) { return FindFProperty<FProperty>(Struct->StructType,Pin->PinName); }
	return nullptr;
}
bool ReadNumber(const FString& Text,int32& Raw)
{
	const TCHAR* Cursor=*Text;
	return MT2SemanticSerialization::ReadInt32Token(Cursor,Raw) && !*Cursor;
}
template<typename T> void ExportSelection(const T& Value,FString& Text)
{
	Text.Reset();
	T::StaticStruct()->ExportText(Text,&Value,nullptr,nullptr,PPF_None,nullptr);
}
bool ConvertDefault(const UEdGraphPin* Pin,const FEdGraphPinType& Type,const FString& Old,FString& Out)
{
	Out=Old;
	if (Pin->Direction==EGPD_Output && Old.IsEmpty()) { return true; }
	if (Type.ContainerType!=EPinContainerType::None) { return false; }
	const FString Text=Old.IsEmpty() ? (Pin->AutogeneratedDefaultValue.IsEmpty() ? TEXT("0") : Pin->AutogeneratedDefaultValue) : Old;
	int32 Raw=0;
	if (auto* Enum=Cast<UEnum>(Type.PinSubCategoryObject.Get()))
	{
		if (!ReadNumber(Text,Raw))
		{
			const int64 Named=Enum->GetValueByNameString(Text);
			if (Named==INDEX_NONE) { return false; }
			Raw=static_cast<int32>(Named);
		}
		if (Enum==StaticEnum<EMT2WeaponSubType>() && Raw==INDEX_NONE) { Raw=static_cast<int32>(EMT2WeaponSubType::None); }
		if (auto* Call=Cast<UK2Node_CallFunction>(Pin->GetOwningNode()); Call && Call->GetTargetFunction() &&
			Call->GetTargetFunction()->GetFName()==TEXT("HasEffectFlag") && Pin->PinName==TEXT("Flag"))
		{
			uint32 Mask=static_cast<uint32>(Raw);
			if (Mask==1 || (Mask && (Mask & (Mask-1)))) { return false; }
			Raw=0; while (Mask>1) { Mask>>=1; ++Raw; }
		}
		if (!Enum->IsValidEnumValue(Raw) || Raw>=Enum->GetMaxEnumValue()) { return false; }
		Out=Enum->GetNameStringByValue(Raw); return true;
	}
	if (auto* Struct=Cast<UScriptStruct>(Type.PinSubCategoryObject.Get()))
	{
		if (!ReadNumber(Text,Raw)) { return false; }
		if (Struct==FMT2ItemAddonSelection::StaticStruct()) { ExportSelection(FMT2ItemAddonSelection::FromLegacy(Raw),Out); }
		else if (Struct==FMT2ItemUniqueSubtypeSelection::StaticStruct()) { ExportSelection(FMT2ItemUniqueSubtypeSelection::FromLegacy(Raw),Out); }
		else if (Struct==FMT2LegacySkillClassSelection::StaticStruct()) { ExportSelection(FMT2LegacySkillClassSelection::FromLegacy(Raw),Out); }
		else if (Struct==FMT2AffectIdentifier::StaticStruct()) { ExportSelection(FMT2AffectIdentifier::FromLegacyId(Raw),Out); }
		else if (Struct==FMT2ItemSubtype::StaticStruct())
		{
			const auto* Family=Pin->GetOwningNode()->FindPin(TEXT("ItemType"));
			if (!Family && Pin->ParentPin) { Family=Pin->GetOwningNode()->FindPin(*(Pin->ParentPin->PinName.ToString()+TEXT("_ItemType"))); }
			if (!Family || !Family->LinkedTo.IsEmpty()) { return false; }
			int32 Kind=0;
			if (!ReadNumber(Family->DefaultValue,Kind)) { Kind=static_cast<int32>(StaticEnum<EMT2ItemType>()->GetValueByNameString(Family->DefaultValue)); }
			if (Kind<0 || Kind>static_cast<int32>(EMT2ItemType::Belt)) { return false; }
			ExportSelection(FMT2ItemSubtype::FromLegacy(static_cast<EMT2ItemType>(Kind),Raw),Out);
		}
		else { return false; }
		return true;
	}
	return false;
}
