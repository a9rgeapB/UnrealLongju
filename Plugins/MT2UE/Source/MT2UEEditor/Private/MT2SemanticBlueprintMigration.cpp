bool Plan(UBlueprint* Blueprint,FPlan& Out,TArray<FString>& Issues)
{
	Out.Pins.Reset();
	const auto* Schema=GetDefault<UEdGraphSchema_K2>();
	TMap<UEdGraphPin*,int32> Indices; TArray<UEdGraphPin*> Pending;
	auto Add=[&](UEdGraphPin* Pin,FEdGraphPinType Type)
	{
		Type.bIsConst=Pin->PinType.bIsConst; Type.bIsReference=Pin->PinType.bIsReference;
		if (const int32* Index=Indices.Find(Pin))
		{
			if (!SameType(Out.Pins[*Index].Type,Type)) { Issues.Add(TEXT("Conflicting enum domains at ")+Describe(Pin)); }
			return;
		}
		FPinChange Change; Change.Pin=Pin; Change.Type=Type;
		if (!ConvertDefault(Pin,Type,Pin->DefaultValue,Change.DefaultValue)) { Issues.Add(TEXT("Cannot map default at ")+Describe(Pin)); return; }
		Indices.Add(Pin,Out.Pins.Add(MoveTemp(Change))); Pending.Add(Pin);
	};
	TArray<UEdGraph*> Graphs; Blueprint->GetAllGraphs(Graphs);
	for (auto* Graph : Graphs) for (UEdGraphNode* Node : Graph->Nodes) if (Node) for (auto* Pin : Node->Pins) if (Pin)
	{
		FProperty* Property=DeclaredProperty(Pin);
		if (!Property || Property->GetOwnerStruct()->GetOutermost()->GetName()!=TEXT("/Script/Metin2")) { continue; }
		FEdGraphPinType Desired;
		if (Schema->ConvertPropertyToPinType(Property,Desired) && !SameType(Pin->PinType,Desired)) { Add(Pin,Desired); }
	}
	for (int32 Index=0;Index<Pending.Num();++Index)
	{
		UEdGraphPin* Pin=Pending[Index]; const FEdGraphPinType Type=Out.Pins[Indices.FindChecked(Pin)].Type;
		for (auto* Linked : Pin->LinkedTo)
		{
			if (auto* Knot=Cast<UK2Node_Knot>(Linked->GetOwningNode()))
			{ for (auto* KnotPin : Knot->Pins) { Add(KnotPin,Type); } }
		}
	}
	for (const auto& Change : Out.Pins) for (auto* Linked : Change.Pin->LinkedTo)
	{
		const int32* Index=Indices.Find(Linked);
		const auto& Type=Index ? Out.Pins[*Index].Type : Linked->PinType;
		if (!SameType(Change.Type,Type)) { Issues.Add(TEXT("Cannot migrate link ")+Describe(Change.Pin)+TEXT(" -> ")+Describe(Linked)); }
	}
	return Issues.IsEmpty();
}
bool Compile(UBlueprint* Blueprint,TArray<FString>& Issues)
{
	TStrongObjectPtr<UBlueprint> KeepAlive(Blueprint);
	FCompilerResultsLog Log;
	FKismetEditorUtilities::CompileBlueprint(Blueprint,EBlueprintCompileOptions::SkipGarbageCollection,&Log);
	if (Log.NumErrors || Blueprint->Status==BS_Error) { Issues.Add(TEXT("Blueprint compile failed: ")+Blueprint->GetPathName()); return false; }
	return true;
}
bool Apply(UBlueprint* Blueprint,const FPlan& Plan,TArray<FString>& Issues)
{
	struct FIdentity { UK2Node* Node; FName Name; EEdGraphPinDirection Direction; FGuid Id; FString Default; };
	TArray<FIdentity> Identities; TSet<UK2Node*> Nodes;
	for (const auto& Change : Plan.Pins)
	{
		auto* Node=CastChecked<UK2Node>(Change.Pin->GetOwningNode()); Nodes.Add(Node);
		Identities.Add({Node,Change.Pin->PinName,Change.Pin->Direction,Change.Pin->PinId,Change.DefaultValue});
		Change.Pin->PinType=Change.Type; Change.Pin->DefaultValue=Change.DefaultValue;
	}
	for (auto* Node : Nodes) { Node->ReconstructNode(); }
	for (const auto& Identity : Identities)
	{
		UEdGraphPin* Pin=Identity.Node->FindPin(Identity.Name,Identity.Direction);
		if (!Pin) { Issues.Add(TEXT("Reconstruction lost pin ")+Identity.Name.ToString()); return false; }
		Pin->PinId=Identity.Id; Pin->DefaultValue=Identity.Default;
	}
	if (!Plan.Pins.IsEmpty()) { FBlueprintEditorUtils::MarkBlueprintAsModified(Blueprint); }
	return Compile(Blueprint,Issues);
}
bool EquivalentDefault(const UEdGraphPin* Pin,const FString& OldDefault)
{
	if (Pin->DefaultValue==OldDefault) { return true; }
	FString Converted;
	return ConvertDefault(Pin,Pin->PinType,OldDefault,Converted) && Converted==Pin->DefaultValue;
}
